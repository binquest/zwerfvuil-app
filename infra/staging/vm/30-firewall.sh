#!/usr/bin/env bash
# Firewall (nftables): everything inbound closed except SSH from the LAN,
# HTTPS on the tailnet, and Tailscale's WireGuard port.
#
#   LAN_CIDR=192.168.x.0/24 30-firewall.sh   apply; rolled back after 5 minutes
#   30-firewall.sh confirm                    keep it (after a new SSH login worked)
#
# stagingctl passes LAN_CIDR from infra/staging/.env and BQ_SSH_FROM (the
# address the current SSH session comes from).
. "$(dirname "$0")/lib.sh"

if [ "${1:-}" = "confirm" ]; then
  disarm_rollback firewall
  exit 0
fi

LAN_CIDR="${LAN_CIDR:-}"
is_ipv4_cidr "$LAN_CIDR" || die "set LAN_CIDR (e.g. 192.168.1.0/24) in infra/staging/.env"

# Refuse rules that would lock out the session that is applying them.
if [ -n "${BQ_SSH_FROM:-}" ]; then
  [[ "$BQ_SSH_FROM" =~ ^[0-9.]+$ ]] && ip_in_cidr "$BQ_SSH_FROM" "$LAN_CIDR" ||
    die "this SSH session comes from $BQ_SSH_FROM, which is outside LAN_CIDR $LAN_CIDR (SSH is LAN-only)"
fi
vm_ip=$(ip -4 -o route get 1.1.1.1 | sed -n 's/.* src \([0-9.]*\).*/\1/p')
ip_in_cidr "$vm_ip" "$LAN_CIDR" || warn "the VM's own address $vm_ip is outside LAN_CIDR $LAN_CIDR"

if [ "$(systemctl is-enabled nftables.service 2>/dev/null || true)" != "masked" ]; then
  log "masking nftables.service: stopping it would flush the rules of Docker and Tailscale"
  systemctl mask nftables.service >/dev/null
fi

vars=$(mktemp)
printf '# Generated by infra/staging/vm/30-firewall.sh from infra/staging/.env\ndefine LAN_CIDR = %s\n' "$LAN_CIDR" >"$vars"
mkdir -p /etc/bq
if ! cmp -s "$vars" /etc/bq/firewall-vars.nft; then
  install -m 644 "$vars" /etc/bq/firewall-vars.nft
  log "wrote /etc/bq/firewall-vars.nft"
  CHANGED=1
fi
rm -f "$vars"
install_file etc/bq/firewall.nft 644
install_file etc/systemd/system/bq-firewall.service 644

nft -c -f /etc/bq/firewall.nft || die "nft rejected /etc/bq/firewall.nft"

if [ "$CHANGED" = 1 ] || ! nft list table inet bq_filter >/dev/null 2>&1; then
  systemctl daemon-reload
  arm_rollback firewall 300 "systemctl disable bq-firewall.service; nft delete table inet bq_filter"
  systemctl enable bq-firewall.service >/dev/null
  systemctl reload-or-restart bq-firewall.service
  log "firewall applied; open a NEW SSH session, then run: 30-firewall.sh confirm"
fi

nft list table inet bq_filter
