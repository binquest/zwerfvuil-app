#!/usr/bin/env bash
# Self-hosted Supabase (official supabase/docker, pinned) as bq-supabase.service.
#
# Layout on the VM:
#   /opt/binquest/upstream          sparse checkout of supabase/supabase (docker/
#                                   only) at SUPABASE_REF; never modified
#   /opt/binquest/compose           our override, settings.env, host.env, SUPABASE_REF
#   /opt/binquest/secrets           supabase.env: every secret, generated here once
#   /opt/binquest/data/db           Postgres data (system disk)
#   /opt/binquest/data/snippets     Studio SQL snippets
#   /opt/binquest/functions         edge functions (upstream main router + ours)
#   /srv/bq-data/storage            Storage objects = photos (data disk)
#
# Secrets are never printed. Run 40-datadisk, 50-docker and 60-tailscale first.
. "$(dirname "$0")/lib.sh"

BQ=/opt/binquest
UPSTREAM_REPO=https://github.com/supabase/supabase.git
UPSTREAM="$BQ/upstream"
SECRETS="$BQ/secrets/supabase.env"
NODE_IMAGE=node:22-alpine
REF=$(tr -d '[:space:]' <"$BQ_FILES/opt/binquest/compose/SUPABASE_REF")
[[ "$REF" =~ ^[0-9a-f]{40}$ ]] || die "SUPABASE_REF is not a full commit SHA"

mountpoint -q "$BQ_DATA" && [ -f "$BQ_DATA_MARKER" ] && [ -d "$BQ_DATA/storage" ] ||
  die "data disk not mounted; run 40-datadisk.sh first"
systemctl is-active --quiet docker || die "docker is not running; run 50-docker.sh first"
ts_name=$(tailscale status --json 2>/dev/null | jq -r '.Self.DNSName // empty' | sed 's/\.$//')
[[ "$ts_name" == *.ts.net ]] || die "no MagicDNS name from tailscale; run 60-tailscale.sh first"

command -v git >/dev/null || apt-get -q -y install git

# --- upstream checkout ---------------------------------------------------------
if [ ! -d "$UPSTREAM/.git" ]; then
  log "cloning supabase/supabase (docker/ only)"
  git clone -q --filter=blob:none --no-checkout --sparse "$UPSTREAM_REPO" "$UPSTREAM"
  git -C "$UPSTREAM" sparse-checkout set docker
fi
if [ "$(git -C "$UPSTREAM" rev-parse HEAD 2>/dev/null)" != "$REF" ]; then
  log "checking out supabase/supabase $REF"
  git -C "$UPSTREAM" cat-file -e "$REF^{commit}" 2>/dev/null || git -C "$UPSTREAM" fetch -q origin "$REF"
  git -C "$UPSTREAM" -c advice.detachedHead=false checkout -q "$REF"
fi
[ -z "$(git -C "$UPSTREAM" status --porcelain)" ] || die "$UPSTREAM has local changes; it must stay pristine"

# --- our files -----------------------------------------------------------------
install_file opt/binquest/compose/SUPABASE_REF 644
install_file opt/binquest/compose/docker-compose.bq.yml 644
install_file opt/binquest/compose/settings.env 644
install_file usr/local/sbin/bq-compose 755
install_file etc/systemd/system/bq-supabase.service 644

host_env=$(mktemp)
cat >"$host_env" <<EOF
# Generated by infra/staging/vm/70-supabase.sh from the Tailscale MagicDNS name.
SUPABASE_PUBLIC_URL=https://$ts_name
API_EXTERNAL_URL=https://$ts_name/auth/v1
SITE_URL=https://$ts_name
EOF
cmp -s "$host_env" "$BQ/compose/host.env" || { install -m 644 "$host_env" "$BQ/compose/host.env"; log "wrote $BQ/compose/host.env"; }
rm -f "$host_env"

install -d -m 755 "$BQ/data" "$BQ/data/snippets" "$BQ/functions"
install -d -m 700 "$BQ/data/db"
# The upstream router (main) and the shared import map; our own functions are
# added next to it by the deploy step and left alone here.
install -d -m 755 "$BQ/functions/main"
install -m 644 "$UPSTREAM/docker/volumes/functions/main/index.ts" "$BQ/functions/main/index.ts"
[ -f "$BQ/functions/deno.jsonc" ] || install -m 644 "$UPSTREAM/docker/volumes/functions/deno.jsonc" "$BQ/functions/deno.jsonc"

# --- secrets -------------------------------------------------------------------
SECRET_KEYS=(POSTGRES_PASSWORD JWT_SECRET ANON_KEY SERVICE_ROLE_KEY
  SUPABASE_PUBLISHABLE_KEY SUPABASE_SECRET_KEY ANON_KEY_ASYMMETRIC SERVICE_ROLE_KEY_ASYMMETRIC
  JWT_KEYS JWT_JWKS DASHBOARD_PASSWORD SECRET_KEY_BASE REALTIME_DB_ENC_KEY VAULT_ENC_KEY
  PG_META_CRYPTO_KEY LOGFLARE_PUBLIC_ACCESS_TOKEN LOGFLARE_PRIVATE_ACCESS_TOKEN
  S3_PROTOCOL_ACCESS_KEY_ID S3_PROTOCOL_ACCESS_KEY_SECRET)

b64url() { openssl enc -base64 -A | tr '+/' '-_' | tr -d '='; }
hs256_jwt() { # <payload json> <secret>
  local data
  data="$(printf '%s' '{"alg":"HS256","typ":"JWT"}' | b64url).$(printf '%s' "$1" | b64url)"
  printf '%s.%s' "$data" "$(printf '%s' "$data" | openssl dgst -binary -sha256 -hmac "$2" | b64url)"
}

generate_secrets() {
  # Same algorithms as upstream utils/generate-keys.sh and add-new-auth-keys.sh,
  # but written straight to the file instead of printed.
  local jwt_secret iat exp asym
  jwt_secret=$(openssl rand -base64 30)
  iat=$(date +%s)
  exp=$((iat + 5 * 365 * 24 * 3600))
  docker image inspect "$NODE_IMAGE" >/dev/null 2>&1 || docker pull -q "$NODE_IMAGE" >/dev/null
  asym=$(docker run --rm --network none -e JWT_SECRET="$jwt_secret" "$NODE_IMAGE" node -e '
const crypto = require("crypto");
const jwtSecret = process.env.JWT_SECRET;
const { privateKey } = crypto.generateKeyPairSync("ec", { namedCurve: "P-256" });
const jwk = privateKey.export({ format: "jwk" });
const kid = crypto.randomUUID();
const oct = { kty: "oct", k: Buffer.from(jwtSecret).toString("base64url"), alg: "HS256" };
const ec = { kty: "EC", kid, use: "sig", alg: "ES256", ext: true, crv: jwk.crv, x: jwk.x, y: jwk.y };
const keys = [{ ...ec, key_ops: ["sign", "verify"], d: jwk.d }, oct];
const jwks = { keys: [{ ...ec, key_ops: ["verify"] }, oct] };
const sign = (payload) => {
  const data = Buffer.from(JSON.stringify({ alg: "ES256", typ: "JWT", kid })).toString("base64url") + "." +
    Buffer.from(JSON.stringify(payload)).toString("base64url");
  return data + "." + crypto.sign("SHA256", Buffer.from(data), { key: privateKey, dsaEncoding: "ieee-p1363" }).toString("base64url");
};
const iat = Math.floor(Date.now() / 1000), exp = iat + 5 * 365 * 24 * 3600;
const opaque = (prefix) => {
  const body = prefix + crypto.randomBytes(17).toString("base64url").slice(0, 22);
  return body + "_" + crypto.createHash("sha256").update("supabase-self-hosted|" + body).digest("base64url").slice(0, 8);
};
console.log("SUPABASE_PUBLISHABLE_KEY=\x27" + opaque("sb_publishable_") + "\x27");
console.log("SUPABASE_SECRET_KEY=\x27" + opaque("sb_secret_") + "\x27");
console.log("ANON_KEY_ASYMMETRIC=\x27" + sign({ role: "anon", iss: "supabase", iat, exp }) + "\x27");
console.log("SERVICE_ROLE_KEY_ASYMMETRIC=\x27" + sign({ role: "service_role", iss: "supabase", iat, exp }) + "\x27");
console.log("JWT_KEYS=\x27" + JSON.stringify(keys) + "\x27");
console.log("JWT_JWKS=\x27" + JSON.stringify(jwks) + "\x27");
')
  cat <<EOF
# Secrets of the Supabase stack on binquest-staging. Generated once on
# $(date -Iseconds) by infra/staging/vm/70-supabase.sh. Never copy this file
# off the VM; the only other copy is the Proxmox vzdump of the VM.
POSTGRES_PASSWORD='$(openssl rand -hex 24)'
JWT_SECRET='$jwt_secret'
ANON_KEY='$(hs256_jwt "{\"role\":\"anon\",\"iss\":\"supabase\",\"iat\":$iat,\"exp\":$exp}" "$jwt_secret")'
SERVICE_ROLE_KEY='$(hs256_jwt "{\"role\":\"service_role\",\"iss\":\"supabase\",\"iat\":$iat,\"exp\":$exp}" "$jwt_secret")'
$asym
DASHBOARD_PASSWORD='$(openssl rand -hex 16)'
SECRET_KEY_BASE='$(openssl rand -base64 48 | tr -d '\n')'
REALTIME_DB_ENC_KEY='$(openssl rand -hex 8)'
VAULT_ENC_KEY='$(openssl rand -hex 16)'
PG_META_CRYPTO_KEY='$(openssl rand -base64 24)'
LOGFLARE_PUBLIC_ACCESS_TOKEN='$(openssl rand -base64 24)'
LOGFLARE_PRIVATE_ACCESS_TOKEN='$(openssl rand -base64 24)'
S3_PROTOCOL_ACCESS_KEY_ID='$(openssl rand -hex 16)'
S3_PROTOCOL_ACCESS_KEY_SECRET='$(openssl rand -hex 32)'
EOF
}

env_value() { # <file> <key>: the value of key, without surrounding quotes
  sed -n "s/^$2=//p" "$1" | tail -1 | sed -e "s/^'\(.*\)'$/\1/" -e 's/^"\(.*\)"$/\1/'
}

install -d -m 700 "$BQ/secrets"
if [ ! -f "$SECRETS" ]; then
  log "generating new secrets in $SECRETS"
  tmp=$(mktemp "$BQ/secrets/.supabase.env.XXXXXX")
  trap 'rm -f "$tmp"' EXIT
  chmod 600 "$tmp"
  generate_secrets >"$tmp"
  mv "$tmp" "$SECRETS"
  trap - EXIT
else
  log "secrets exist; keeping $SECRETS"
fi
chmod 600 "$SECRETS"
chown root:root "$SECRETS"

# Every secret must be set and differ from the upstream example value.
example="$UPSTREAM/docker/.env.example"
for key in "${SECRET_KEYS[@]}"; do
  value=$(env_value "$SECRETS" "$key")
  [ -n "$value" ] || die "secret $key is empty"
  [ "$value" != "$(env_value "$example" "$key")" ] || die "secret $key still has the upstream default"
done
[ "$(env_value "$SECRETS" VAULT_ENC_KEY | tr -d '\n' | wc -c)" = 32 ] || die "VAULT_ENC_KEY must be 32 characters"
[ "$(env_value "$SECRETS" REALTIME_DB_ENC_KEY | tr -d '\n' | wc -c)" = 16 ] || die "REALTIME_DB_ENC_KEY must be 16 characters"
log "secrets checked: ${#SECRET_KEYS[@]} set, none equal to the upstream defaults"

# --- compose config checks -----------------------------------------------------
bq-compose config --quiet
published=$(bq-compose config --format json | jq -r '
  .services | to_entries[] | .key as $s | (.value.ports // [])[] |
  "\($s) \(.host_ip // "0.0.0.0") \(.published) \(.target)"')
log "published ports:"
echo "$published" | sed 's/^/    /'
if echo "$published" | awk 'NF && $2 != "127.0.0.1"' | grep -q .; then
  die "a port is published on something other than 127.0.0.1"
fi
running_services=$(bq-compose config --services | sort | paste -sd' ')
log "services: $running_services"

# --- start ---------------------------------------------------------------------
log "pulling images (first run: several GB)"
bq-compose pull --quiet
systemctl daemon-reload
systemctl enable bq-supabase.service >/dev/null
if systemctl is-active --quiet bq-supabase.service; then
  log "bq-supabase is running; applying changes"
  bq-compose up --detach --wait --wait-timeout 600 --remove-orphans
else
  log "starting bq-supabase (waits until every container is healthy)"
  systemctl start bq-supabase.service
fi
bq-compose ps --format 'table {{.Service}}\t{{.Status}}\t{{.Ports}}'
